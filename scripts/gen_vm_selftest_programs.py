#!/usr/bin/env python3
"""Assemble the ring-3 demand-paging self-test programs into a C header.

Usage: gen_vm_selftest_programs.py [--check] OUTPUT.h
With --check the header is regenerated in memory and compared to OUTPUT.h;
a mismatch exits non-zero so CI catches stale generated bytes.
"""
import pathlib, subprocess, sys, tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "kernel/selftest/vm"
BASE = 0x8000000000
LAYOUT = {
    "ANON": BASE + 0x100000,      # 64 pages RW demand-zero
    "RO": BASE + 0x200000,        # 1 page, read-only demand-zero
    "GUARD": BASE + 0x300000,     # 1 page guard
    "OOMWIN": BASE + 0x500000,    # 4 pages RW demand-zero (failure injection)
    "SYSBUF": BASE + 0x600000,    # 1 page RW demand-zero (syscall prefault)
    "GAP": BASE + 0x700000,       # reserved by no region
    "DATA": BASE + 0x100000,      # ELF data segment (own address space)
    "MMAPLOW": BASE + 0x1000000000,  # lowest address mmap may return
}
PROGRAMS = [
    "zero_rw", "exec_anon", "ro_write_first", "ro_read_then_write",
    "guard_read", "gap_read", "kernel_read", "kernel_write",
    "kernel_high_read", "noncanonical", "oom_touch", "syscall_prefault",
    "stack_grow", "bss_check",
    "mmap_basic", "mmap_use_after_unmap", "brk_grow_shrink",
]

def assemble(name):
    with tempfile.TemporaryDirectory() as tmp:
        out = pathlib.Path(tmp) / (name + ".bin")
        cmd = ["nasm", "-f", "bin", "-I", str(SRC) + "/",
               str(SRC / (name + ".asm")), "-o", str(out)]
        for key, value in LAYOUT.items():
            cmd.append("-D%s=0x%X" % (key, value))
        subprocess.run(cmd, check=True)
        return out.read_bytes()

def render():
    lines = [
        "/* Generated by scripts/gen_vm_selftest_programs.py; do not edit. */",
        "#ifndef VM_SELFTEST_PROGRAMS_H",
        "#define VM_SELFTEST_PROGRAMS_H",
        "#include <stdint.h>", "",
    ]
    for key, value in LAYOUT.items():
        lines.append("#define VMT_%s 0x%XULL" % (key, value))
    lines.append("")
    for name in PROGRAMS:
        code = assemble(name)
        if name == "zero_rw":
            assert code[0:2] == b"\x41\xbf" and code[6:8] == b"\x41\xbe", \
                "zero_rw patch offsets moved"
        if name == "stack_grow":
            assert code[0] == 0xB9, "stack_grow patch offset moved"
        lines.append("static const uint8_t vmt_prog_%s[] = {" % name)
        for i in range(0, len(code), 12):
            lines.append("    " + ", ".join("0x%02X" % b for b in code[i:i+12]) + ",")
        lines.append("};")
    lines += ["", "#define VMT_ZERO_RW_PATTERN_OFFSET 2U",
              "#define VMT_ZERO_RW_COUNT_OFFSET 8U",
              "#define VMT_STACK_GROW_COUNT_OFFSET 1U", "", "#endif", ""]
    return "\n".join(lines)

def main():
    args = sys.argv[1:]
    check = "--check" in args
    args = [a for a in args if a != "--check"]
    target = pathlib.Path(args[0])
    text = render()
    if check:
        if not target.exists() or target.read_text() != text:
            print("%s is stale; run scripts/gen_vm_selftest_programs.py" % target)
            return 1
        return 0
    target.write_text(text)
    return 0

if __name__ == "__main__":
    sys.exit(main())
