const uint8_t* symbol_glyph(char c)
{
    switch (c)
    {
        case '/': return glyph_slash;
        case '.': return glyph_dot;
        case '-': return glyph_dash;
        case '_': return glyph_underscore;
        case ':': return glyph_colon;
        case '+': return glyph_plus;
        case '=': return glyph_equal;
        case '>': return glyph_greater;
        case '<': return glyph_less;
        case '[': return glyph_bracket_open;
        case ']': return glyph_bracket_close;
        default: return 0;
    }
}



int lowercase_font_index(char c)
{
    if (c >= 'a' && c <= 'z')
        return c - 'a';

    return -1;
}
int font_index(char c)
{
    if (c >= 'a' && c <= 'z')
        c = (char)(c - 'a' + 'A');

    if (c >= 'A' && c <= 'Z')
        return c - 'A';

    if (c >= '0' && c <= '9')
        return 26 + (c - '0');

    return -1;
}

void graphics_draw_text(
    int x,
    int y,
    const char* text,
    uint32_t color,
    unsigned int scale
)
{
    if (!initialized || !text || scale == 0U ||
        scale > (unsigned int)(INT_MAX / 8))
        return;

    const int scale_i = (int)scale;
    const uint32_t packed = graphics_pack_color(color);
    int64_t pen_x = x;
    int64_t pen_y = y;
    const int64_t line_x = x;

    while (*text)
    {
        char c = *text++;

        if (c == '\n')
        {
            pen_y += 8 * (int64_t)scale_i;
            pen_x = line_x;
            continue;
        }

        if (c == ' ')
        {
            pen_x += 6 * (int64_t)scale_i;
            continue;
        }

        int index = font_index(c);
        int lower_index = lowercase_font_index(c);
        const uint8_t* glyph = 0;

        if (lower_index >= 0)
            glyph = lowercase_font[lower_index];
        else if (index >= 0)
            glyph = font[index];
        else
            glyph = symbol_glyph(c);

        if (!glyph)
        {
            pen_x += 6 * (int64_t)scale_i;
            continue;
        }

        int dirty_x0 = (int)framebuffer_width;
        int dirty_y0 = (int)framebuffer_height;
        int dirty_x1 = -1;
        int dirty_y1 = -1;

        /*
         * Rasterize directly into the shadow buffer. Calling fill_rect for
         * each lit glyph pixel repeatedly packed the same color and updated
         * the damage bitmap for overlapping tiles. Track changed pixels and
         * publish one damage rectangle per glyph instead.
         */
        for (int row = 0; row < 7; row++)
        {
            uint8_t bits = glyph[row];
            int col = 0;
            while (col < 5)
            {
                while (col < 5 && (bits & (1U << (4 - col))) == 0U)
                    col++;
                if (col >= 5)
                    break;

                int run_start = col++;
                while (col < 5 && (bits & (1U << (4 - col))) != 0U)
                    col++;

                int64_t run_x0 = pen_x + (int64_t)run_start * scale_i;
                int64_t run_x1 = pen_x + (int64_t)col * scale_i;
                if (run_x0 < 0)
                    run_x0 = 0;
                if (run_x1 > framebuffer_width)
                    run_x1 = framebuffer_width;
                if (run_x0 >= run_x1)
                    continue;

                int64_t pixel_y0 = pen_y + (int64_t)row * scale_i;
                for (int sy = 0; sy < scale_i; sy++)
                {
                    int64_t draw_y = pixel_y0 + sy;
                    if (draw_y < 0 || draw_y >= framebuffer_height)
                        continue;

                    volatile uint32_t* dest = (volatile uint32_t*)(
                        framebuffer + (size_t)draw_y * framebuffer_pitch);
                    for (int64_t draw_x = run_x0; draw_x < run_x1; draw_x++)
                    {
                        uint32_t px = (uint32_t)draw_x;
                        if (dest[px] == packed)
                            continue;

                        dest[px] = packed;
                        if ((int)px < dirty_x0) dirty_x0 = (int)px;
                        if ((int)px > dirty_x1) dirty_x1 = (int)px;
                        if ((int)draw_y < dirty_y0)
                            dirty_y0 = (int)draw_y;
                        if ((int)draw_y > dirty_y1)
                            dirty_y1 = (int)draw_y;
                    }
                }
            }
        }

        if (dirty_x1 >= dirty_x0 && dirty_y1 >= dirty_y0)
            graphics_mark_damage(dirty_x0, dirty_y0,
                                 dirty_x1 - dirty_x0 + 1,
                                 dirty_y1 - dirty_y0 + 1);

        pen_x += 6 * (int64_t)scale_i;
    }
}